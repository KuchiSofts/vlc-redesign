"""Generates the platform files from design/tokens.json:

    design/build/tokens.css    CSS custom properties (web, Samsung TV)
    design/build/colors.xml    Android colour resources
    design/build/Tokens.swift  Swift constants (iPhone, iPad, Apple TV)

    python design/tools/export.py            # write them
    python design/tools/export.py --check    # exit 1 if they are stale

Standard library only.
"""

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TOKENS = ROOT / "design" / "tokens.json"
BUILD = ROOT / "design" / "build"
HEADER = "Generated by design/tools/export.py from design/tokens.json ({version}). Do not edit."


def walk(node, path=(), inherited=None):
    if not isinstance(node, dict):
        return
    kind = node.get("$type", inherited)
    if "$value" in node:
        yield path, node, kind
        return
    for key, child in node.items():
        if not key.startswith("$"):
            yield from walk(child, path + (key,), kind)


def kebab(part):
    return re.sub(r"(?<=[a-z0-9])([A-Z])", r"-\1", part).lower()


def camel(parts):
    words = []
    for p in parts:
        words += re.sub(r"(?<=[a-z0-9])([A-Z])", r" \1", p).replace("-", " ").split()
    text = words[0].lower() + "".join(w[:1].upper() + w[1:] for w in words[1:])
    return "_" + text if text[0].isdigit() else text


def css_value(token, kind):
    v = token["$value"]
    if kind == "shadow":
        return f"{v['offsetX']} {v['offsetY']} {v['blur']} {v['spread']} {v['color']}"
    if kind == "fontFamily":
        return ", ".join(f'"{f}"' if " " in f else f for f in v)
    return str(v)


def css(tokens, version):
    lines = [f"/* {HEADER.format(version=version)} */", "", ":root {"]
    for path, token, kind in walk(tokens):
        lines.append(f"  --vlc-{'-'.join(kebab(p) for p in path)}: {css_value(token, kind)};")
    lines += ["}", "", "/* The theme's colours under one name: dark by default, light with data-theme=\"light\" */"]
    for theme, selector in (("dark", ":root, [data-theme=\"dark\"]"), ("light", "[data-theme=\"light\"]")):
        lines.append(selector + " {")
        for path, token, kind in walk(tokens["color"][theme], ()):
            name = "-".join(kebab(p) for p in path)
            lines.append(f"  --vlc-theme-{name}: var(--vlc-color-{theme}-{name});")
        lines.append("}")
    return "\n".join(lines) + "\n"


def android_color(hex_color):
    h = hex_color.lstrip("#").upper()
    return "#" + (h[6:8] + h[:6] if len(h) == 8 else "FF" + h)


def android(tokens, version):
    lines = ['<?xml version="1.0" encoding="utf-8"?>', f"<!-- {HEADER.format(version=version)} -->", "<resources>"]
    for path, token, kind in walk(tokens):
        if kind != "color":
            continue
        name = "vlc_" + "_".join(kebab(p).replace("-", "_") for p in path)
        desc = token.get("$description", "").replace("--", "-")
        lines.append(f"    <!-- {desc} -->")
        lines.append(f'    <color name="{name}">{android_color(token["$value"])}</color>')
    lines.append("</resources>")
    return "\n".join(lines) + "\n"


def swift_literal(token, kind):
    v = token["$value"]
    if kind == "color":
        h = v.lstrip("#")
        a = int(h[6:8], 16) / 255 if len(h) == 8 else 1
        return f"VLCColor(0x{h[:6].upper()}, alpha: {a:g})"
    if kind == "dimension":
        return f"{float(re.match(r'-?[0-9.]+', v).group(0)):g}"
    if kind == "shadow":
        c = v["color"].lstrip("#")
        a = int(c[6:8], 16) / 255 if len(c) == 8 else 1
        n = lambda s: f"{float(re.match(r'-?[0-9.]+', s).group(0)):g}"
        return (f"VLCShadow(color: VLCColor(0x{c[:6].upper()}, alpha: {a:.4g}), x: {n(v['offsetX'])}, "
                f"y: {n(v['offsetY'])}, blur: {n(v['blur'])}, spread: {n(v['spread'])})")
    if kind == "fontFamily":
        return json.dumps(v[0])
    return f"{v:g}" if isinstance(v, float) else str(v)


def swift(tokens, version):
    out = [f"// {HEADER.format(version=version)}", "", "import Foundation", "",
           "/// An sRGB colour of the design: 0xRRGGBB and an alpha.",
           "public struct VLCColor: Equatable {",
           "    public let red: Double, green: Double, blue: Double, alpha: Double",
           "    public init(_ rgb: UInt32, alpha: Double = 1) {",
           "        red = Double((rgb >> 16) & 0xFF) / 255",
           "        green = Double((rgb >> 8) & 0xFF) / 255",
           "        blue = Double(rgb & 0xFF) / 255",
           "        self.alpha = alpha",
           "    }",
           "}", "",
           "/// A drop shadow of the design (points).",
           "public struct VLCShadow: Equatable {",
           "    public let color: VLCColor",
           "    public let x: Double, y: Double, blur: Double, spread: Double",
           "}", "",
           "/// The design tokens; sizes in points (1 Figma px).",
           "public enum VLCTokens {",
           f"    public static let version = {json.dumps(version)}"]
    for group in (k for k in tokens if not k.startswith("$")):
        out += ["", f"    public enum {group[:1].upper() + group[1:]} {{"]
        for path, token, kind in walk(tokens[group]):
            desc = token.get("$description", "")
            out.append(f"        /// {desc}")
            out.append(f"        public static let {camel(path)} = {swift_literal(token, kind)}")
        out.append("    }")
    out.append("}")
    return "\n".join(out) + "\n"


def generate():
    tokens = json.loads(TOKENS.read_text(encoding="utf-8"))
    version = tokens["$extensions"]["org.vlc-redesign"]["version"]
    return {
        "tokens.css": css(tokens, version),
        "colors.xml": android(tokens, version),
        "Tokens.swift": swift(tokens, version),
    }


def compare():
    problems = []
    for name, text in generate().items():
        path = BUILD / name
        if not path.exists():
            problems.append(f"missing: design/build/{name}")
        elif path.read_bytes().replace(b"\r\n", b"\n") != text.encode("utf-8"):
            problems.append(f"stale: design/build/{name}")
    return problems


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if design/build is stale")
    args = parser.parse_args()
    if args.check:
        problems = compare()
        for p in problems:
            print(p)
        return 1 if problems else 0
    BUILD.mkdir(parents=True, exist_ok=True)
    for name, text in generate().items():
        (BUILD / name).write_bytes(text.encode("utf-8"))
        print(f"wrote design/build/{name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
